#!/usr/bin/env node
// Generates web/public/food-filters.js from the Swift lists in PickerCore, so
// the web page and the app recognize fast food, coffee & sweets, stores that
// aren't restaurants, and cuisine labels the same way. ONE source of truth:
// edit the Swift files, then run
//
//   node web/tools/make-food-filters.mjs          (writes the file)
//   node web/tools/make-food-filters.mjs --check  (fails if it's out of date)
//
// web/tools/test-food-filters.mjs checks the JS gives the same answers as the
// Swift tests.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const core = join(root, "Packages/PickerCore/Sources/PickerCore");
const out = join(root, "web/public/food-filters.js");

const read = (file) => readFileSync(join(core, file), "utf8")
  // Drop // comments so a commented-out name doesn't sneak in.
  .replace(/\/\/[^\n]*/g, "");

/** The string literals in `static let <name>...= [ ... ]`. */
function stringArray(source, name) {
  const start = source.search(new RegExp(`static let ${name}\\b[^=]*=\\s*\\[`));
  if (start < 0) throw new Error(`Couldn't find ${name}`);
  let i = source.indexOf("[", source.indexOf("=", start));
  let depth = 0, end = i;
  for (; end < source.length; end++) {
    if (source[end] === "[") depth++;
    else if (source[end] === "]" && --depth === 0) break;
  }
  return strings(source.slice(i, end + 1));
}

function strings(text) {
  return [...text.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => JSON.parse(`"${m[1]}"`));
}

function cuisineRules(source) {
  const body = source.slice(source.indexOf("static let rules"));
  const block = body.slice(0, body.indexOf("\n    ]") + 6);
  return [...block.matchAll(/\(\s*"([^"]+)"\s*,\s*\[([\s\S]*?)\]\s*\)/g)]
    .map((m) => [m[1], strings(m[2])]);
}

export function generate() {
  const fast = read("FastFood.swift");
  const sweets = read("CoffeeAndSweets.swift");
  const notRestaurant = read("NotARestaurant.swift");
  const label = read("CuisineLabel.swift");
  const data = {
    fastFoodChains: stringArray(fast, "chains"),
    fastFoodPhrases: stringArray(fast, "selfDescribed"),
    sweetsChains: stringArray(sweets, "chains"),
    sweetsWords: stringArray(sweets, "nameWords"),
    notRestaurantPrefixes: stringArray(notRestaurant, "prefixes"),
    notRestaurantExact: stringArray(notRestaurant, "exactNames"),
    cuisineRules: cuisineRules(label),
  };
  for (const [k, v] of Object.entries(data)) if (!v.length) throw new Error(`Empty list: ${k}`);
  const json = (v) => JSON.stringify(v);
  return `// GENERATED by web/tools/make-food-filters.mjs from Packages/PickerCore (FastFood,
// CoffeeAndSweets, NotARestaurant, CuisineLabel). Don't edit by hand: change
// the Swift lists and run the script again.

const FAST_FOOD_CHAINS = ${json(data.fastFoodChains)};
const FAST_FOOD_PHRASES = ${json(data.fastFoodPhrases)};
const SWEETS_CHAINS = ${json(data.sweetsChains)};
const SWEETS_WORDS = ${json(data.sweetsWords)};
const NOT_RESTAURANT_PREFIXES = ${json(data.notRestaurantPrefixes)};
const NOT_RESTAURANT_EXACT = ${json(data.notRestaurantExact)};
const CUISINE_RULES = ${json(data.cuisineRules)};

/** FastFood.normalize: lowercase, "&" → "and", drop apostrophes, other punctuation → spaces. */
export function normalize(text) {
  const lowered = String(text).toLowerCase().replaceAll("&", " and ").replaceAll("’", "").replaceAll("'", "");
  return lowered.replace(/[^\\p{L}\\p{N}]/gu, " ").split(" ").filter(Boolean).join(" ");
}
/** String.folding(.diacriticInsensitive): "Café" → "Cafe". */
function fold(text) { return String(text).normalize("NFD").replace(/\\p{M}/gu, ""); }

const norm = (list) => list.map(normalize);
const fastChains = norm(FAST_FOOD_CHAINS);
const sweetsChains = norm(SWEETS_CHAINS);
const sweetsWords = norm(SWEETS_WORDS);
const storePrefixes = norm(NOT_RESTAURANT_PREFIXES);
const storeExact = new Set(norm(NOT_RESTAURANT_EXACT));
const startsWithOne = (n, list) => list.some((c) => n === c || n.startsWith(c + " "));
const hasPhrase = (padded, list) => list.some((w) => padded.includes(\` \${w} \`));

export function isFastFood(name) {
  const n = normalize(name);
  return hasPhrase(\` \${n} \`, FAST_FOOD_PHRASES) || startsWithOne(n, fastChains);
}

export function isCoffeeOrSweets(name, category = "") {
  const n = normalize(fold(name));
  if (startsWithOne(n, sweetsChains)) return true;
  if (hasPhrase(\` \${n} \`, sweetsWords)) return true;
  return category === "Dessert";
}

export function isNotARestaurant(name) {
  const n = normalize(name);
  return storeExact.has(n) || startsWithOne(n, storePrefixes);
}

export function guessCuisine(name) {
  const padded = \` \${normalize(fold(name))} \`;
  for (const [label, keys] of CUISINE_RULES) if (hasPhrase(padded, keys)) return label;
  return isFastFood(name) ? "Fast food" : null;
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--check")) {
    const current = readFileSync(out, "utf8");
    if (current !== text) {
      console.error("web/public/food-filters.js is out of date. Run: node web/tools/make-food-filters.mjs");
      process.exit(1);
    }
    console.log("food-filters.js matches the Swift lists.");
  } else {
    writeFileSync(out, text);
    console.log("Wrote web/public/food-filters.js");
  }
}
